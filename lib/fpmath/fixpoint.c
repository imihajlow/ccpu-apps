fp32 fp32_28_umul(fp32 a, fp32 b);

fp32 fp32_28_mul(fp32 a, fp32 b) {
    bool negate_result = false;
    if (a < 0) {
        a = -a;
        negate_result = true;
    }
    if (b < 0) {
        b = -b;
        negate_result = !negate_result;
    }
    fp32 r = fp32_28_umul(a, b);
    if (negate_result) {
        r = -r;
    }
    return r;
}

fp16 fp16_12_umul(fp16 a, fp16 b);

fp16 fp16_12_mul(fp16 a, fp16 b) {
    bool negate_result = false;
    if (a < 0) {
        a = -a;
        negate_result = true;
    }
    if (b < 0) {
        b = -b;
        negate_result = !negate_result;
    }
    fp16 r = fp16_12_umul(a, b);
    if (negate_result) {
        r = -r;
    }
    return r;
}

static const fp16 rc_table[];
static const fp16 sin_table[];

fp16 fp16_12_rc(fp16 a) {
    if (a < 0) {
        uint8_t i = (-a) >> 8;
        return -rc_table[i];
    } else {
        uint8_t i = a >> 8;
        return rc_table[i];
    }
}

fp16 fp16_12_sin(int8_t phi) {
    if (phi >= 0) {
        return sin_table[phi];
    } else {
        return -sin_table[-phi];
    }
}

fp16 fp16_12_cos(int8_t phi) {
    return fp16_12_sin(phi + 64);
}

